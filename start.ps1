# MAILOX self-hosted, Docker path (Windows): install and start, then open http://localhost:8080
# Everything runs on this machine and listens on 127.0.0.1 only.
#   .\start.ps1          start (first run builds the images, a few minutes)
#   .\start.ps1 stop     stop
#   .\start.ps1 logs     follow the logs
#
# Configuration written on first run:
#   .env                 POSTGRES_PASSWORD and MAILOX_PORT (read by docker compose)
#   backend\.env.docker  API / worker settings (env_file of docker-compose.yml)
# backend\.env belongs to the manual install (setup-selfhosted.ps1) and is not used here.
param([string]$Action = "start")
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

# Port given in the environment wins over the one saved in .env
$EnvPort = $env:MAILOX_PORT

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Host "Docker Desktop is required: https://docs.docker.com/desktop/install/windows-install/"
    exit 1
}
docker compose version *> $null
if ($LASTEXITCODE -ne 0) { Write-Host "Docker Compose v2 is required (docker compose)."; exit 1 }

if ($Action -eq "stop") { docker compose down; exit 0 }
if ($Action -eq "logs") { docker compose logs -f; exit 0 }

function New-Secret {
    $bytes = New-Object byte[] 32
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    ($bytes | ForEach-Object { $_.ToString("x2") }) -join ""
}

# First run: generate the configuration with fresh secrets
if (-not (Test-Path ".env")) {
    $FirstPort = if ($EnvPort) { $EnvPort } else { "8080" }
    "POSTGRES_PASSWORD=$(New-Secret)`nMAILOX_PORT=$FirstPort" | Set-Content -Encoding ascii ".env"
}
$FilePort = ((Get-Content ".env" | Where-Object { $_ -like "MAILOX_PORT=*" }) -split "=", 2)[1]
$Port = if ($EnvPort) { $EnvPort } elseif ($FilePort) { $FilePort.Trim() } else { "8080" }
$env:MAILOX_PORT = $Port
$Url = "http://localhost:$Port"
$PgPassword = ((Get-Content ".env" | Where-Object { $_ -like "POSTGRES_PASSWORD=*" }) -split "=", 2)[1]

$DockerEnv = "backend/.env.docker"
if (-not (Test-Path $DockerEnv)) {
    $Legacy = (Test-Path "backend/.env") -and ((Get-Content "backend/.env" -TotalCount 1) -like "# Generated by start.*")
    if ($Legacy) {
        # Install made by an older start script: keep its keys (stored data is encrypted
        # with MASTER_ENCRYPTION_KEY), pin ALLOWED_HOSTS.
        (Get-Content "backend/.env") -replace '^ALLOWED_HOSTS=.*', 'ALLOWED_HOSTS=localhost,127.0.0.1' |
            Set-Content -Encoding ascii $DockerEnv
        Write-Host "Migrated backend/.env (written by an older start script) to $DockerEnv"
    } else {
        if (Test-Path "backend/.env") {
            Write-Host "Note: backend/.env (manual install) is ignored by the Docker stack, which uses $DockerEnv."
        }
        @"
# Generated by start.ps1 - Docker path, self-hosted, local machine only
MAILOX_EDITION=selfhosted
DATABASE_URL=postgresql+asyncpg://mailox:$PgPassword@db:5432/mailox
DATABASE_URL_SYNC=postgresql+psycopg2://mailox:$PgPassword@db:5432/mailox
REDIS_URL=redis://redis:6379/0
CELERY_BROKER_URL=redis://redis:6379/0
CELERY_RESULT_BACKEND=redis://redis:6379/1
SECRET_KEY=$(New-Secret)
REFRESH_SECRET_KEY=$(New-Secret)
MASTER_ENCRYPTION_KEY=$(New-Secret)
DEBUG=false
ALLOWED_ORIGINS=$Url,http://127.0.0.1:$Port
ALLOWED_HOSTS=localhost,127.0.0.1
FRONTEND_URL=$Url
WEB_ACTIVE_PROBE_ENABLED=true
CRED_PROBE_ENABLED=true
"@ | Set-Content -Encoding ascii $DockerEnv
        Write-Host "Configuration written to $DockerEnv"
    }
}

Write-Host "Starting MAILOX (the first start builds the images and takes a few minutes)..."
docker compose up -d --build
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host -NoNewline "Waiting for MAILOX"
for ($i = 0; $i -lt 120; $i++) {
    try {
        Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "$Url/api/v1/meta" | Out-Null
        Write-Host ""
        Write-Host "MAILOX is running: $Url"
        Write-Host "First start: create the admin account with"
        Write-Host "  docker compose exec api python -m app.cli create-admin you@example.com"
        Start-Process $Url
        exit 0
    } catch {
        Write-Host -NoNewline "."
        Start-Sleep -Seconds 3
    }
}
Write-Host ""
Write-Host "MAILOX did not answer in time. Check: .\start.ps1 logs"
exit 1
