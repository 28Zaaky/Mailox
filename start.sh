#!/usr/bin/env bash
# MAILOX self-hosted, Docker path: install and start, then open http://localhost:8080
# Everything runs on this machine and listens on 127.0.0.1 only.
#   ./start.sh          start (first run builds the images, a few minutes)
#   ./start.sh stop     stop
#   ./start.sh logs     follow the logs
#
# Configuration written on first run:
#   .env                 POSTGRES_PASSWORD and MAILOX_PORT (read by docker compose)
#   backend/.env.docker  API / worker settings (env_file of docker-compose.yml)
# backend/.env belongs to the manual install (setup-selfhosted.sh) and is not used here.
set -euo pipefail
cd "$(dirname "$0")"

# Port given in the environment wins over the one saved in .env
ENV_PORT="${MAILOX_PORT:-}"

command -v docker >/dev/null 2>&1 || { echo "Docker is required: https://docs.docker.com/get-docker/"; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required (docker compose)."; exit 1; }

case "${1:-start}" in
  stop) docker compose down; exit 0 ;;
  logs) docker compose logs -f; exit 0 ;;
esac

rand() {
  if command -v openssl >/dev/null 2>&1; then openssl rand -hex 32
  else python3 -c "import secrets; print(secrets.token_hex(32))"; fi
}

# First run: generate the compose configuration with a fresh database password
if [ ! -f .env ]; then
  echo "POSTGRES_PASSWORD=$(rand)" > .env
  echo "MAILOX_PORT=${ENV_PORT:-8080}" >> .env
fi
# shellcheck disable=SC1091
. ./.env

PORT="${ENV_PORT:-${MAILOX_PORT:-8080}}"
export MAILOX_PORT="${PORT}"
URL="http://localhost:${PORT}"

if [ ! -f backend/.env.docker ]; then
  if [ -f backend/.env ] && head -n 1 backend/.env | grep -q "^# Generated by start\."; then
    # Install made by an older start script: keep its keys (stored data is encrypted
    # with MASTER_ENCRYPTION_KEY), pin ALLOWED_HOSTS.
    sed -e "s/^ALLOWED_HOSTS=.*/ALLOWED_HOSTS=localhost,127.0.0.1/" backend/.env > backend/.env.docker
    echo "Migrated backend/.env (written by an older start script) to backend/.env.docker"
  else
    if [ -f backend/.env ]; then
      echo "Note: backend/.env (manual install) is ignored by the Docker stack, which uses backend/.env.docker."
    fi
    cat > backend/.env.docker <<EOF
# Generated by start.sh - Docker path, self-hosted, local machine only
MAILOX_EDITION=selfhosted
DATABASE_URL=postgresql+asyncpg://mailox:${POSTGRES_PASSWORD}@db:5432/mailox
DATABASE_URL_SYNC=postgresql+psycopg2://mailox:${POSTGRES_PASSWORD}@db:5432/mailox
REDIS_URL=redis://redis:6379/0
CELERY_BROKER_URL=redis://redis:6379/0
CELERY_RESULT_BACKEND=redis://redis:6379/1
SECRET_KEY=$(rand)
REFRESH_SECRET_KEY=$(rand)
MASTER_ENCRYPTION_KEY=$(rand)
DEBUG=false
ALLOWED_ORIGINS=${URL},http://127.0.0.1:${PORT}
ALLOWED_HOSTS=localhost,127.0.0.1
FRONTEND_URL=${URL}
WEB_ACTIVE_PROBE_ENABLED=true
CRED_PROBE_ENABLED=true
EOF
    echo "Configuration written to backend/.env.docker"
  fi
fi

echo "Starting MAILOX (the first start builds the images and takes a few minutes)..."
docker compose up -d --build

printf "Waiting for MAILOX"
for _ in $(seq 1 120); do
  if curl -fs "${URL}/api/v1/meta" >/dev/null 2>&1; then
    echo; echo "MAILOX is running: ${URL}"
    echo "First start: create the admin account with"
    echo "  docker compose exec api python -m app.cli create-admin you@example.com"
    (command -v xdg-open >/dev/null && xdg-open "${URL}") || (command -v open >/dev/null && open "${URL}") || true
    exit 0
  fi
  printf "."; sleep 3
done
echo; echo "MAILOX did not answer in time. Check: ./start.sh logs"; exit 1
